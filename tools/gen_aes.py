#!/usr/bin/env python3
"""Generate aes128.v (byte-serial AES-128 enc+dec, on-the-fly key schedule).
S-box tables emitted from the verified SBOX in aes_xts_ref.py so hardware
tables are bit-identical to the golden model. Review fixes applied:
 - din/dec latched at start; start edge-gated (no auto-retrigger)
 - all functions declared `automatic`."""
from aes_xts_ref import SBOX, INV_SBOX, RCON

def byte(sig, b):
    return f"{sig}[{(15-b)*8} +: 8]"

def sbox_case(name):
    tbl = SBOX if name == "sb" else INV_SBOX
    lines = [f"  function automatic [7:0] {name}; input [7:0] a; begin case(a)"]
    for i in range(0, 256, 8):
        lines.append("    " + " ".join(f"8'h{i+j:02x}:{name}=8'h{tbl[i+j]:02x};" for j in range(8)))
    lines.append(f"    default: {name}=8'h00; endcase end endfunction")
    return "\n".join(lines)

def shiftrows(inv):
    assigns = []
    for o in range(16):
        r, c = o % 4, o // 4
        inp = (((c - r) % 4) if inv else ((c + r) % 4)) * 4 + r
        assigns.append(f"{byte('y',o)} = {byte('s',inp)};")
    name = "inv_srows" if inv else "srows"
    return (f"  function automatic [127:0] {name}; input [127:0] s; reg [127:0] y; begin\n    "
            + "\n    ".join(assigns) + f"\n    {name} = y; end endfunction")

HEAD = r"""// aes128.v -- AES-128 byte-serial core, encrypt + decrypt, on-the-fly key schedule.
// GENERATED by tools/gen_aes.py from model/aes_xts_ref.py -- do not edit by hand.
// One forward + one inverse S-box shared by the whole datapath (state + key schedule),
// one MixColumns column network (InvMixColumns = MixColumns(pre(col))).
//   enc round r=1..10 : SUB(16: sb(x^k[r-1]))  KEY(4: k[r-1]->k[r])  SR(1)  MC(4, r<10)
//   dec setup         : KEY(4) x10 forward to k10, ARK(1: x^=k10)
//   dec round r=10..1 : SR(1: inv)  KEY(4: k[r]->k[r-1])  SUB(16: isb(x)^k[r-1])  MC(4, r>1)
//   then FIN(1): dout <= enc ? x^k10 : x.  Latency: enc 248 clk, dec 289 clk from start to done.
// shortcut: two LUT S-boxes (fwd+inv); a shared composite-field S-box is the next area step.
`default_nettype none

module aes128 (
    input  wire         clk,
    input  wire         rst_n,
    input  wire         start,
    input  wire         dec,
    input  wire [127:0] key,
    input  wire [127:0] din,
    output reg  [127:0] dout,
    output reg          busy,
    output reg          done
);
"""

GF = r"""
  function automatic [7:0] xt; input [7:0] a; begin xt = a[7] ? ((a<<1)^8'h1b) : (a<<1); end endfunction
  function automatic [31:0] mixc; input [31:0] c; reg [7:0] a0,a1,a2,a3; begin
    a0=c[31:24]; a1=c[23:16]; a2=c[15:8]; a3=c[7:0];
    mixc = { xt(a0)^(xt(a1)^a1)^a2^a3, a0^xt(a1)^(xt(a2)^a2)^a3,
             a0^a1^xt(a2)^(xt(a3)^a3), (xt(a0)^a0)^a1^a2^xt(a3) };
  end endfunction
  // InvMixColumns(c) == mixc(imc_pre(c))
  function automatic [31:0] imc_pre; input [31:0] c; reg [7:0] u,v; begin
    u = xt(xt(c[31:24]^c[15:8])); v = xt(xt(c[23:16]^c[7:0]));
    imc_pre = c ^ {u,v,u,v}; end endfunction
"""

def rcon_case():
    body = "".join(f"4'd{i+1}:rcon=8'h{v:02x}; " for i, v in enumerate(RCON))
    return f"  function automatic [7:0] rcon; input [3:0] r; begin case(r)\n    {body}\n    default:rcon=8'h00; endcase end endfunction"

FSM = r"""
  localparam P_SUB = 3'd0, P_KEY = 3'd1, P_SR = 3'd2, P_MC = 3'd3, P_ARK = 3'd4, P_FIN = 3'd5;
  reg [127:0] st, rk;
  reg [3:0]   rnd, cnt;
  reg [2:0]   ph;
  reg         mode, setup, start_d;
  wire        start_pulse = start & ~start_d & ~busy;

  // key step (4 clk, one S-box byte per clk). w0 rotates by a byte per clk so byte j is on top.
  // reverse (k[r] -> k[r-1]) first turns w1..w3 into a1^a0, a2^a1, a3^a2 at j=0.
  wire        krev = mode & ~setup;
  wire [31:0] w3x  = (krev && cnt[1:0] == 2'd0) ? (rk[31:0] ^ rk[63:32]) : rk[31:0];
  wire [7:0]  kb   = (cnt[1:0] == 2'd0) ? w3x[23:16] : (cnt[1:0] == 2'd1) ? w3x[15:8] :
                     (cnt[1:0] == 2'd2) ? w3x[7:0]   : w3x[31:24];               // RotWord
  wire [7:0]  sbo  = sb((ph == P_KEY) ? kb : (st[127:120] ^ rk[127:120]));       // shared fwd S-box
  wire [7:0]  ktop = rk[127:120] ^ sbo ^ ((cnt[1:0] == 2'd0) ? rcon(rnd) : 8'h00);
  wire [31:0] w0n  = {rk[119:96], ktop};
  wire [7:0]  subo = mode ? (isb(st[127:120]) ^ rk[127:120]) : sbo;
  wire [127:0] ark = st ^ rk;

  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      st<=0; rk<=0; rnd<=0; cnt<=0; ph<=P_SUB; mode<=0; setup<=0; start_d<=0;
      busy<=0; done<=0; dout<=0;
    end else begin
      done    <= 1'b0;
      start_d <= start;
      if (start_pulse) begin
        st <= din; rk <= key; mode <= dec; setup <= dec; busy <= 1'b1;
        rnd <= 4'd1; cnt <= 4'd0; ph <= dec ? P_KEY : P_SUB;
      end else if (busy) begin
        case (ph)
          P_SUB: begin
            st <= {st[119:0], subo}; rk <= {rk[119:0], rk[127:120]}; cnt <= cnt + 4'd1;
            if (cnt == 4'd15) ph <= !mode ? P_KEY : (rnd == 4'd1) ? P_FIN : P_MC;
          end
          P_KEY: begin
            cnt <= cnt + 4'd1;
            if (krev && cnt[1:0] == 2'd0)
              rk <= {w0n, rk[95:64]^rk[127:96], rk[63:32]^rk[95:64], rk[31:0]^rk[63:32]};
            else if (!krev && cnt[1:0] == 2'd3)
              rk <= {w0n, w0n^rk[95:64], w0n^rk[95:64]^rk[63:32], w0n^rk[95:64]^rk[63:32]^rk[31:0]};
            else
              rk <= {w0n, rk[95:0]};
            if (cnt[1:0] == 2'd3) begin
              cnt <= 4'd0;
              if (setup) begin if (rnd == 4'd10) ph <= P_ARK; else rnd <= rnd + 4'd1; end
              else ph <= mode ? P_SUB : P_SR;
            end
          end
          P_SR: begin
            st <= mode ? inv_srows(st) : srows(st);
            ph <= mode ? P_KEY : (rnd == 4'd10) ? P_FIN : P_MC;
          end
          P_MC: begin
            st <= {st[95:0], mixc(mode ? imc_pre(st[127:96]) : st[127:96])}; cnt <= cnt + 4'd1;
            if (cnt[1:0] == 2'd3) begin
              cnt <= 4'd0;
              if (mode) begin rnd <= rnd - 4'd1; ph <= P_SR; end
              else      begin rnd <= rnd + 4'd1; ph <= P_SUB; end
            end
          end
          P_ARK: begin st <= ark; setup <= 1'b0; ph <= P_SR; end
          default: begin   // P_FIN
            dout <= mode ? st : ark; done <= 1'b1; busy <= 1'b0;
          end
        endcase
      end
    end
  end
endmodule
`default_nettype wire
"""

def main():
    parts = [HEAD, sbox_case("sb"), sbox_case("isb"), shiftrows(False), shiftrows(True), GF, rcon_case(), FSM]
    out = "\n".join(parts) + "\n"
    open("aes128.v","w").write(out)
    print("wrote aes128.v:", out.count(chr(10)), "lines")

if __name__ == "__main__":
    main()
